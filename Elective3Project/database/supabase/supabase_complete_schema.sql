-- =====================================================================
-- NOTES
-- =====================================================================
-- 
-- Column Specifications:
-- 
-- USERS TABLE:
--   - id: Primary key, auto-incrementing bigint
--   - username: 50 char max, unique, alphanumeric + underscore
--   - full_name: 100 char max, user's full name
--   - email: 100 char max, unique email address
--   - contact_number: 11 char max (nullable), unique, Philippine phone format (09XXXXXXXXX)
--   - role: 'admin' or 'attendee' (default: 'attendee')
--   - password: 255 char max, bcrypt hashed
--   - remember_token: 100 char max, for "remember me" functionality
--   - created_at: Timestamp when record was created
--   - updated_at: Timestamp when record was last updated
--
-- EVENTS TABLE:
--   - id: Primary key, auto-incrementing bigint
--   - event_name: 100 char max, required event name
--   - description: Long text field for event details
--   - event_date: Date when event occurs
--   - start_time: Time when event starts
--   - end_time: Time when event ends
--   - venue: 150 char max, event location/venue
--   - max_slots: Integer, maximum registration capacity (must be > 0)
--   - created_at: Timestamp when record was created
--   - updated_at: Timestamp when record was last updated
--
-- REGISTRATIONS TABLE:
--   - id: Primary key, auto-incrementing bigint
--   - event_id: Foreign key to events table (cascade delete)
--   - first_name: 50 char max, attendee first name
--   - last_name: 50 char max, attendee last name
--   - email: 100 char max, attendee email
--   - contact_number: 11 char max, phone number (digits only)
--   - attendance_status: 'Pending', 'Present', or 'Absent' (default: 'Pending')
--   - created_at: Timestamp when record was created
--   - updated_at: Timestamp when record was last updated
--
-- UNIQUE CONSTRAINTS:
--   - users.username: No duplicate usernames
--   - users.email: No duplicate emails
--   - users.contact_number: No duplicate phone numbers
--   - registrations(event_id, email): No duplicate registrations per event
