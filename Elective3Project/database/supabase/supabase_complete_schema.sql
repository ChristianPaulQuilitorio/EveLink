-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =====================================================================
-- ENUMS
-- =====================================================================

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'attendance_status_enum') THEN
        CREATE TYPE attendance_status_enum AS ENUM ('Pending', 'Present', 'Absent');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_role_enum') THEN
        CREATE TYPE user_role_enum AS ENUM ('admin', 'attendee');
    END IF;
END $$;

-- =====================================================================
-- USERS TABLE (Updated with contact_number and role)
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    contact_number VARCHAR(11) UNIQUE,
    role user_role_enum NOT NULL DEFAULT 'attendee',
    password VARCHAR(255) NOT NULL,
    remember_token VARCHAR(100),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- Create indexes for users table
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);
CREATE INDEX IF NOT EXISTS idx_users_role ON public.users(role);
CREATE INDEX IF NOT EXISTS idx_users_contact_number ON public.users(contact_number);

-- =====================================================================
-- EVENTS TABLE
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name VARCHAR(100) NOT NULL,
    description TEXT,
    event_date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE,
    end_time TIME WITHOUT TIME ZONE,
    venue VARCHAR(150) NOT NULL,
    max_slots INTEGER NOT NULL CHECK (max_slots > 0),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

-- Create indexes for events table
CREATE INDEX IF NOT EXISTS idx_events_event_date ON public.events(event_date);
CREATE INDEX IF NOT EXISTS idx_events_event_name ON public.events(event_name);

-- =====================================================================
-- REGISTRATIONS TABLE
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    contact_number VARCHAR(11) NOT NULL,
    attendance_status attendance_status_enum NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT registrations_event_email_unique UNIQUE (event_id, email),
    CONSTRAINT registrations_contact_number_digits CHECK (contact_number ~ '^[0-9]{11}$')
);

-- Create indexes for registrations table
CREATE INDEX IF NOT EXISTS idx_registrations_event_id ON public.registrations(event_id);
CREATE INDEX IF NOT EXISTS idx_registrations_email ON public.registrations(email);
CREATE INDEX IF NOT EXISTS idx_registrations_attendance_status ON public.registrations(attendance_status);
CREATE INDEX IF NOT EXISTS idx_registrations_created_at ON public.registrations(created_at DESC);

-- =====================================================================
-- VIEWS
-- =====================================================================

CREATE OR REPLACE VIEW public.v_dashboard_stats AS
SELECT
    (SELECT COUNT(*) FROM public.events) AS total_events,
    (SELECT COUNT(*) FROM public.registrations) AS total_registrations,
    (
        SELECT COUNT(*)
        FROM public.events e
        WHERE (
            SELECT COUNT(*)
            FROM public.registrations r
            WHERE r.event_id = e.id
        ) >= e.max_slots
    ) AS full_events,
    (
        SELECT COUNT(*)
        FROM public.events
        WHERE event_date >= CURRENT_DATE
    ) AS upcoming_events;

